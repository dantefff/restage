#!/usr/bin/env bash
#
# net.sh — network autoconfiguration capture.
#
# Before rebooting into the installer, we record the current system's
# addressing so the runtime installer can configure the network without the
# provider's DHCP being available (or being slow). The captured configuration
# is rendered into a tiny POSIX script injected into the initrd.
#
# Two operating modes are produced:
#   * static: explicit addresses + gateways (used when addresses are static)
#   * dhcp:   udhcpc fallback (used when the machine was itself on DHCP)
#
# shellcheck shell=bash

rs_import lib/common.sh

RS_NET_IFACE=""
RS_IPV4_ADDR=""
RS_IPV4_GW=""
RS_IPV6_ADDR=""
RS_IPV6_GW=""
RS_IPV4_DNS=""

# First interface with an IPv4 address on the default route.
rs_net_primary_iface() {
    local iface
    if command -v ip >/dev/null 2>&1; then
        iface="$(ip route show default 2>/dev/null | awk '/^default/{print $5; exit}')"
        [[ -n "${iface}" ]] && { printf '%s\n' "${iface}"; return 0; }
        # Fallback: any up interface with a global address.
        iface="$(ip -o addr show scope global 2>/dev/null | awk '/inet /{print $2; exit}')"
        [[ -n "${iface}" ]] && { printf '%s\n' "${iface}"; return 0; }
    fi
    return 1
}

# CIDR of the primary address on $1 (e.g. 192.0.2.10/24).
rs_net_iface_cidr_v4() {
    ip -o addr show dev "${1}" scope global 2>/dev/null | awk '/inet /{print $4; exit}'
}

rs_net_iface_cidr_v6() {
    ip -o addr show dev "${1}" scope global 2>/dev/null | awk '/inet6 /{split($4,a,"/"); print $4; exit}'
}

# Gateway (v4/v6) on the default route for $1.
rs_net_gateway_v4() {
    ip route show dev "${1}" 2>/dev/null | awk '/^default/{print $3; exit}'
}

rs_net_gateway_v6() {
    ip -6 route show dev "${1}" 2>/dev/null | awk '/^default/{print $3; exit}'
}

# Nameservers for $1 as a space-separated list. Tries systemd-resolved,
# then /etc/resolv.conf (skipping the stub), then the netplan config.
rs_net_dns_v4() {
    local dns=""
    if command -v resolvectl >/dev/null 2>&1; then
        dns="$(resolvectl dns "${1}" 2>/dev/null | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}' | tr '\n' ' ' | sed 's/ $//')"
    fi
    if [[ -z "${dns}" ]]; then
        dns="$(awk '/^nameserver/{print $2}' /etc/resolv.conf 2>/dev/null | grep -vE '^(127\.|::1$)' | tr '\n' ' ' | sed 's/ $//')"
    fi
    if [[ -z "${dns}" ]]; then
        dns="$(grep -rhA3 'nameservers:' /etc/netplan/ 2>/dev/null | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}' | tr '\n' ' ' | sed 's/ $//')"
    fi
    printf '%s\n' "${dns}"
}

# Capture networking state into RS_NET_* globals.
rs_net_capture() {
    local iface
    iface="$(rs_net_primary_iface)" || {
        rs_log_warn "could not detect a primary network interface; installer will rely on DHCP"
        return 0
    }
    RS_NET_IFACE="${iface}"
    RS_IPV4_ADDR="$(rs_net_iface_cidr_v4 "${iface}")"
    RS_IPV6_ADDR="$(rs_net_iface_cidr_v6 "${iface}")"
    RS_IPV4_GW="$(rs_net_gateway_v4 "${iface}")"
    RS_IPV6_GW="$(rs_net_gateway_v6 "${iface}")"
    RS_IPV4_DNS="$(rs_net_dns_v4 "${iface}")"
    rs_log_debug "net: iface=${RS_NET_IFACE} v4=${RS_IPV4_ADDR:-dhcp} gw4=${RS_IPV4_GW:-none} v6=${RS_IPV6_ADDR:-none} gw6=${RS_IPV6_GW:-none} dns=${RS_IPV4_DNS:-none}"
}

# Decide static vs dhcp: RS_NET_DHCP in {auto, yes, no}.
rs_net_is_dhcp() {
    case "${RS_NET_DHCP:-auto}" in
        yes | 1 | true)
            return 0
            ;;
        no | 0 | false)
            return 1
            ;;
    esac
    # auto: if we captured a global IPv4 address, prefer static; else DHCP.
    if [[ -n "${RS_IPV4_ADDR}" ]]; then
        return 1
    fi
    return 0
}

# Render a POSIX shell script that configures $1 (iface) using RS_NET_*.
rs_net_render_script() {
    local iface="${1:-${RS_NET_IFACE}}"
    printf '#!/bin/sh\n'
    printf '# generated by restage net.sh\n'
    printf 'IFACE="%s"\n' "${iface}"

    # printf 'IFACE="%s"\n' "${iface}"
    # printf 'if ! ip link show "$IFACE" >/dev/null 2>&1; then\n'
    # printf '    IFACE="$(ls /sys/class/net | grep -E "^(eth|enp|ens|eno)" | head -n1)"\n'
    # printf '    echo "configured iface not found, falling back to $IFACE"\n'
    # printf 'fi\n'

    printf 'try_iface() {'
    printf '  [ -n "$1" ] && ip link show "$1" >/dev/null 2>&1 && { echo "$1"; return 0; }'
    printf '  return 1'
    printf '}'
    printf 'for cand in "${RS_NET_IFACE:-}" eth0 \'
    printf '       $(ls /sys/class/net | grep -E "^(enp|ens|eno|eth)" | head -n1); do'
    printf '  if try_iface "$cand"; then IFACE="$cand"; break; fi'
    printf 'done'

    if rs_net_is_dhcp; then
        printf 'udhcpc -q -i "$IFACE" 2>/dev/null || true\n'
        printf 'if [ -x /sbin/udhcpc6 ] || command -v udhcpc6 >/dev/null 2>&1; then\n'
        printf '    udhcpc6 -q -i "$IFACE" 2>/dev/null || true\n'
        printf 'fi\n'
    else
        printf 'ip link set "$IFACE" up\n'
        if [[ -n "${RS_IPV4_ADDR}" ]]; then
            printf 'ip addr replace %s dev "$IFACE" 2>/dev/null || ip addr add %s dev "$IFACE"\n' \
                "${RS_IPV4_ADDR}" "${RS_IPV4_ADDR}"
        fi
        if [[ -n "${RS_IPV4_GW}" ]]; then
            printf 'ip route replace default via %s dev "$IFACE" 2>/dev/null || ip route add default via %s dev "$IFACE"\n' \
                "${RS_IPV4_GW}" "${RS_IPV4_GW}"
        fi
        if [[ -n "${RS_IPV6_ADDR}" ]]; then
            printf 'ip -6 addr replace %s dev "$IFACE" 2>/dev/null || ip -6 addr add %s dev "$IFACE"\n' \
                "${RS_IPV6_ADDR}" "${RS_IPV6_ADDR}"
        fi
        if [[ -n "${RS_IPV6_GW}" ]]; then
            printf 'ip -6 route replace default via %s dev "$IFACE" 2>/dev/null || ip -6 route add default via %s dev "$IFACE"\n' \
                "${RS_IPV6_GW}" "${RS_IPV6_GW}"
        fi
        if [[ -n "${RS_IPV4_DNS}" ]]; then
            printf 'echo "nameserver %s" > /etc/resolv.conf\n' "${RS_IPV4_DNS%% *}"
        else
            printf 'echo "nameserver 1.1.1.1" > /etc/resolv.conf\n'
            printf 'echo "nameserver 8.8.8.8" >> /etc/resolv.conf\n'
        fi
    fi
    printf ': OK\n'
}
